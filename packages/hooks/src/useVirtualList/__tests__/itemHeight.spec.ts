import { act, cleanup, fireEvent, renderHook } from '@testing-library/react';
import { afterEach, describe, expect, test, vi } from 'vitest';
import type { Options } from '../index';
import useVirtualList from '../index';

afterEach(() => {
  cleanup();
  document.body.innerHTML = '';
  vi.restoreAllMocks();
});

function setup(itemHeight: Options<number>['itemHeight'], inline = false) {
  const container = document.createElement('div');
  const wrapper = document.createElement('div');
  container.appendChild(wrapper);
  document.body.appendChild(container);
  vi.spyOn(container, 'clientHeight', 'get').mockReturnValue(300);
  vi.spyOn(container, 'clientWidth', 'get').mockReturnValue(300);
  const initialList = Array.from({ length: 100 }, (_, index) => index);
  const hook = renderHook(
    ({ height, list }) =>
      useVirtualList(list, {
        containerTarget: container,
        wrapperTarget: wrapper,
        itemHeight:
          inline && typeof height === 'function' ? (index, data) => height(index, data) : height,
        overscan: 0,
      }),
    { initialProps: { height: itemHeight, list: initialList } },
  );
  const rerender = (height: Options<number>['itemHeight'], list = initialList) =>
    hook.rerender({ height, list });
  return { ...hook, rerender, container, wrapper };
}

describe('itemHeight changes', () => {
  test('updates the total scroll area and scrollTo with a new numeric height', () => {
    const { result, rerender, wrapper, container } = setup(30);
    act(() => result.current[1](20));
    expect(wrapper.style.height).toBe('2400px');
    rerender(60);
    act(() => result.current[1](20));
    expect(container.scrollTop).toBe(1200);
    expect(wrapper.style.marginTop).toBe('1200px');
    expect(wrapper.style.height).toBe('4800px');
  });

  test('updates the visible range without a scroll event', () => {
    const { result, rerender } = setup(30);
    expect(result.current[0]).toHaveLength(10);
    rerender(60);
    expect(result.current[0]).toHaveLength(5);
  });

  test('recalculates geometry when the height callback changes', () => {
    const { result, rerender, wrapper } = setup(() => 30);
    act(() => result.current[1](20));
    rerender(() => 60);
    act(() => result.current[1](20));
    expect(wrapper.style.marginTop).toBe('1200px');
    expect(wrapper.style.height).toBe('4800px');
  });

  test('updates the visible range when heights change but total height stays the same', () => {
    const { result, rerender, wrapper } = setup((index) => (index < 50 ? 30 : 60));
    const previousLength = result.current[0].length;
    const totalHeight =
      Number.parseFloat(wrapper.style.height) + Number.parseFloat(wrapper.style.marginTop);
    rerender((index) => (index < 50 ? 60 : 30));
    expect(result.current[0].length).toBeLessThan(previousLength);
    expect(
      Number.parseFloat(wrapper.style.height) + Number.parseFloat(wrapper.style.marginTop),
    ).toBe(totalHeight);
  });

  test('accepts inline height callbacks without repeated state updates', () => {
    const { result, rerender, container, wrapper } = setup(() => 30, true);
    const previousList = result.current[0];
    rerender(() => 30);
    expect(result.current[0]).toBe(previousList);
    rerender(() => 60);
    expect(result.current[0]).toHaveLength(4);
    container.scrollTop = 1200;
    fireEvent.scroll(container);
    expect(result.current[0][0].index).toBe(20);
    expect(wrapper.style.height).toBe('4800px');
  });

  test('handles an empty range and NaN data with inline callbacks', () => {
    const { result, rerender, container } = setup(() => 30, true);
    container.scrollTop = 3000;
    rerender(() => 30, []);
    expect(result.current[0]).toEqual([]);
    container.scrollTop = 0;
    rerender(() => 30, [0, Number.NaN, 2, 3]);
    expect(result.current[0].some((item) => Number.isNaN(item.data))).toBe(true);
  });

  test('keeps data updates when the visible indices stay the same', () => {
    const { result, rerender } = setup(30);
    const next = Array.from({ length: 100 }, (_, index) => index + 100);
    rerender(30, next);
    expect(result.current[0][0]).toEqual({ index: 0, data: 100 });
  });

  test('ignores the scroll event generated by scrollTo, then handles user scrolling', () => {
    const { result, container } = setup(30);
    act(() => result.current[1](20));
    const current = result.current[0];
    fireEvent.scroll(container);
    expect(result.current[0]).toBe(current);
    container.scrollTop = 900;
    fireEvent.scroll(container);
    expect(result.current[0][0].index).toBe(30);
  });

  test('handles unavailable targets and unmeasured containers', () => {
    const list = [1, 2, 3];
    let container: HTMLDivElement | null = null;
    const { result, rerender } = renderHook(
      ({ height }) =>
        useVirtualList(list, {
          containerTarget: () => container,
          wrapperTarget: () => null,
          itemHeight: height,
        }),
      { initialProps: { height: 30 } },
    );
    expect(result.current[0]).toEqual([]);
    act(() => result.current[1](1));
    container = document.createElement('div');
    document.body.appendChild(container);
    rerender({ height: 60 });
    expect(result.current[0]).toEqual([]);
    act(() => result.current[1](0));
    expect(result.current[0]).toHaveLength(3);
    const previousContainer = container;
    container = null;
    fireEvent.scroll(previousContainer);
    fireEvent.scroll(previousContainer);
    rerender({ height: 30 });
  });
});
